FIX = [('著', '着'), ('﹔', '；'), ('﹕', '：'), ('祇', '只'), ('儘', '尽'), ('\"', '"')]

def clean(t):
    for a, b in FIX:
        t = t.replace(a, b)
    t = re.sub(r'[ \t]+', ' ', t)
    t = re.sub(r'”\s+。', '”。', t)
    t = re.sub(r'”\s+，', '”，', t)
    return t.strip()

def seg(key, a, b, n=4):
    ps = E.between(key, a, b, n)
    return [clean(p) for p in ps if clean(p)]


