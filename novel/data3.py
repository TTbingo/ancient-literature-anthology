def seg(key, a, b, drop_tail=None):
    ls = wt.load(key)
    out = []
    for raw in ls[a:b + 1]:
        t = wt.ts(raw)
        t = re.sub(r'^\s*[:：]+\s*', '', t)          # wiki 缩进标记
        t = t.replace('著', '着').replace('麼', '么').replace('麽', '么')
        t = t.replace('籐', '藤').replace('醇𬪩', '醇醲').replace('扑𧈢蜡', '扑蜡')
        t = re.sub(r'\[\[[^\]]*\]\]', '', t)
        t = re.sub(r'[ \t\u3000]+', ' ', t).strip()
        if not t or t in NOISE or len(t) < 2:
            continue
        out.append(t)
    if drop_tail and out and out[-1].endswith(drop_tail):
        out[-1] = out[-1][:-len(drop_tail)]
    return out


