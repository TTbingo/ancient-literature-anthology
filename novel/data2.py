FIX = [('著', '着'), ('﹔', '；'), ('﹕', '：'), ('祇', '只')]

def clean(t):
    for a, b in FIX:
        t = t.replace(a, b)
    t = re.sub(r'[ \t]+', ' ', t)
    t = re.sub(r'”\s+。', '”。', t)
    t = re.sub(r'”\s+，', '”，', t)
    return t.strip()

def seg(key, a, b, n=4, merge_verse=True):
    ps = [clean(p) for p in E.between(key, a, b, n)]
    ps = [p for p in ps if p]
    if merge_verse:
        out = []
        for p in ps:
            # 五七言诗句被切成了独立的短段，并回上一段，用换行分隔
            if out and len(p) <= 18 and re.search(r'[，。]$', p) and '“' not in p and '”' not in p:
                out[-1] = out[-1] + '<br>' + p
            else:
                out.append(p)
        ps = out
    return ps


