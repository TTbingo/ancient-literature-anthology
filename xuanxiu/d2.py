def cut(key, start, n, end=None):
    txt = "".join(E.between(key, start, end))
    if len(txt) <= n:
        return E.split_long(txt, 4)
    c = txt.rfind("。", 0, n)
    return E.split_long(txt[:c + 1] + "……", 4)

