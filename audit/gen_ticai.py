import re
def norm(s):
    s = re.sub(r"（[^）]*）", "", s)      # 去括号后缀：（其四）（节选）（选章）
    s = re.sub(r"[《》〈〉\s·・]", "", s)  # 去书名号与分隔点
    return s
def anchor(title):
    """按显示名取锚点：精确 → 归一化相等 → 归一化包含；多命中报错以人工消歧。"""
    if title in ids:
        return ids[title][0]
    t = norm(title)
    eq = [v[0] for k, v in ids.items() if norm(k) == t]
    if len(eq) == 1:
        return eq[0]
    if len(eq) > 1:
        raise KeyError("锚点歧义：" + title + " => " + " | ".join(eq))
    inc = [(k, v[0]) for k, v in ids.items() if t and t in norm(k)]
    if len(inc) == 1:
        return inc[0][1]
    if len(inc) > 1:
        raise KeyError("锚点多处：" + title + " => " + " | ".join(x[1] for x in inc))
    raise KeyError("未找到锚点：" + title)

